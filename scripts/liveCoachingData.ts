interface ManifestEntry { path: string; dataset_class: string; session_canonical_sha256?: string }

/** Eligible: recorded simulator captures that also have a saved Nebius report. */
export const eligibleCaptures = (): ManifestEntry[] => {
  const manifest = JSON.parse(read('fixtures/provenance.json').toString('utf8')) as ManifestEntry[];
  const reported = new Set(manifest.filter((e) => e.dataset_class === 'saved_provider_report').map((e) => e.session_canonical_sha256));
  return manifest.filter((e) => e.dataset_class === 'recorded_simulator_capture' && reported.has(e.session_canonical_sha256));
};

export const renderLiveCoachingData = async (): Promise<{ server: string; client: string }> => {
  const schema = JSON.parse(read('schemas/coaching-report.v1.schema.json').toString('utf8')) as Record<string, unknown>;
  const sessions: Record<string, LiveSession> = {};
  for (const entry of eligibleCaptures()) {
    const raw = new Uint8Array(read(entry.path));
    const name = entry.path.split('/').pop() ?? entry.path;
    const session = await importSealedSessionFile({ name, size: raw.length, arrayBuffer: async () => raw.buffer }, '1970-01-01T00:00:00.000Z');
    if (session.canonicalSha256 !== entry.session_canonical_sha256) throw new Error(`MANIFEST_DIGEST_MISMATCH ${entry.path}`);
    const bundle = buildSealedEvidenceBundle(session);
    const rendered = await renderLiveRequest(bundle, schema);
    if (rendered.bytes > MAX_OUTBOUND_BODY_BYTES) throw new Error(`LIVE_REQUEST_TOO_LARGE ${entry.path} ${rendered.bytes}`);
    const evidence = PROMPT_EVIDENCE[rendered.sha256];
    if (!evidence || evidence.renderedPromptBytes > INPUT_TOKEN_UPPER_BOUND || evidence.observedPromptTokens > INPUT_TOKEN_UPPER_BOUND) {
      throw new Error(`LIVE_REQUEST_COST_UNPROVEN ${entry.path}`);
    }
    sessions[session.canonicalSha256] = { bundle, requestSha256: rendered.sha256, requestBytes: rendered.bytes, ...evidence };
  }
  const digests = Object.keys(sessions);
  const header = '// Generated by scripts/build-live-coaching-data.ts. Do not edit; rerun the script.\n';
  const server = header
    + "import type { LiveSession } from './liveCoaching.ts';\n\n"
    + `export const LIVE_REPORT_SCHEMA: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};\n\n`
    + `export const LIVE_SESSIONS: Readonly<Record<string, LiveSession>> = ${JSON.stringify(sessions, null, 2)};\n`;
  const client = header
    + '// Captures the hosted live path accepts; the server holds their sealed evidence.\n'
    + `export const LIVE_ELIGIBLE_SESSIONS: readonly string[] = ${JSON.stringify(digests, null, 2)};\n`;
  return { server, client };
};
