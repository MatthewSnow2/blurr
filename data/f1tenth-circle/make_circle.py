"""Draw the rung-2 constant-radius circle track as an F1TENTH gym map.

Stdlib only, deterministic: the same arguments always produce the same bytes.
Output follows the Silverstone layout in f1tenth_racetracks: <Name>_map.png
(8-bit grayscale), <Name>_map.yaml, <Name>_centerline.csv, <Name>_raceline.csv.

Usage: python3 make_circle.py [out_dir]
"""

import math
import struct
import sys
import zlib
from pathlib import Path

NAME = "Circle"
RADIUS_M = 8.0  # centerline radius; car minimum turning radius is about 0.9 m
HALF_WIDTH_M = 1.1  # same as Silverstone's w_tr_right_m / w_tr_left_m
RESOLUTION_M = 0.05  # metres per pixel
EXTENT_M = 12.0  # map spans [-EXTENT_M, EXTENT_M] on both axes
N_POINTS = 500  # waypoints around the loop, about 0.1 m apart
SPEED_MPS = 2.5  # matches the runner's target speed


def write_png_gray(path: Path, rows: list[bytes], width: int) -> None:
    def chunk(kind: bytes, data: bytes) -> bytes:
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))

    raw = b"".join(b"\x00" + row for row in rows)  # filter type 0 per scanline
    ihdr = struct.pack(">IIBBBBB", width, len(rows), 8, 0, 0, 0, 0)
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def main(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    size = round(2 * EXTENT_M / RESOLUTION_M)
    origin = -EXTENT_M

    # PNG rows go top to bottom; the gym flips the image, so the last row is y = origin.
    rows = []
    for row_top in range(size):
        y = origin + (size - 1 - row_top + 0.5) * RESOLUTION_M
        row = bytearray(size)
        for col in range(size):
            x = origin + (col + 0.5) * RESOLUTION_M
            if abs(math.hypot(x, y) - RADIUS_M) <= HALF_WIDTH_M:
                row[col] = 255  # free
        rows.append(bytes(row))
    write_png_gray(out_dir / f"{NAME}_map.png", rows, size)

    (out_dir / f"{NAME}_map.yaml").write_text(
        f"image: {NAME}_map.png\n"
        f"resolution: {RESOLUTION_M}\n"
        f"origin: [{origin}, {origin}, 0.000000]\n"
        "negate: 0\n"
        "occupied_thresh: 0.45\n"
        "free_thresh: 0.196\n"
    )

    # Counter-clockwise from (R, 0). Left turn, so kappa = +1/R (Silverstone: kappa = dpsi/ds).
    center = ["# x_m, y_m, w_tr_right_m, w_tr_left_m"]
    race = [
        f"# blurr {NAME.lower()} r={RADIUS_M} m",
        "# generated by data/f1tenth-circle/make_circle.py",
        "# s_m; x_m; y_m; psi_rad; kappa_radpm; vx_mps; ax_mps2",
    ]
    for i in range(N_POINTS):
        theta = 2 * math.pi * i / N_POINTS
        x, y = RADIUS_M * math.cos(theta), RADIUS_M * math.sin(theta)
        psi = (theta + math.pi / 2) % (2 * math.pi)  # Silverstone keeps psi in [0, 2pi)
        center.append(f"{x!r}, {y!r}, {HALF_WIDTH_M}, {HALF_WIDTH_M}")
        race.append(
            f"{RADIUS_M * theta:.7f};{x:.7f};{y:.7f};{psi:.7f};"
            f"{1 / RADIUS_M:.7f};{SPEED_MPS:.7f};{0.0:.7f}"
        )
    (out_dir / f"{NAME}_centerline.csv").write_text("\n".join(center) + "\n")
    (out_dir / f"{NAME}_raceline.csv").write_text("\n".join(race) + "\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent / NAME)
